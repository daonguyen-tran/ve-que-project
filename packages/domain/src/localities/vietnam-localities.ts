import type { GeoPoint } from '../shared/common-schemas';
import type { StopKind } from '../itinerary/itinerary';

export type VietnamRegion = 'north' | 'center' | 'south';

/** Localité de la liste intégrée (données statiques, embarquées dans l'appli). */
export interface BuiltinLocality {
  /** Identifiant lisible et stable (« hoi-an »). */
  id: string;
  /** Nom usuel en français, tel qu'on l'écrit dans un guide. */
  name: string;
  vietnameseName: string;
  kind: StopKind;
  /** Centre-ville, à quelques centaines de mètres près : assez pour la carte et la météo. */
  location: GeoPoint;
  region: VietnamRegion;
  /** Autres façons courantes de l'écrire (« Saïgon », « Halong »…). */
  aliases?: readonly string[];
}

